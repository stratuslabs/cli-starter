/**
 * A real command name to use in the generated script's comments.
 *
 * Hardcoding one means every adopter's completion file explains itself with a
 * command their CLI does not have — the template's example leaking downstream.
 */
const exampleCommand = (program: ProgramDef): string =>
  visible(program.commands)[0]?.name ?? '<command>';

export const bashCompletions = (program: ProgramDef): string => {
  const entries = walk(program.commands);
  const fn = `_${program.name.replaceAll(/[^A-Za-z0-9]/g, '_')}`;
  const example = exampleCommand(program);

  const cases = entries.map((entry) => {
    const subcommands = visible(entry.command.subcommands ?? []).map((c) => c.name);
    const flags = visibleFlags(entry.command.flags).flatMap(([n, f]) => flagSpellings(n, f));
    return `    ${sq(entry.path.join(' '))}) words=${sq([...subcommands, ...flags].join(' '))} ;;`;
  });

  const roots = visible(program.commands).flatMap(names);
  const globals = visibleFlags(program.globalFlags).flatMap(([n, f]) => flagSpellings(n, f));

  return `# bash completion for ${program.name}
# Generated by \`${program.name} completions bash\` — do not edit.
# Install:  ${program.name} completions bash > /etc/bash_completion.d/${program.name}
#     or:   eval "$(${program.name} completions bash)"   # in ~/.bashrc

${fn}() {
  local cur prev line words
  cur="\${COMP_WORDS[COMP_CWORD]}"

  # The command path typed so far, ignoring flags and their values, so that
  # \`${program.name} --verbose ${example} <TAB>\` resolves the same as \`${program.name} ${example} <TAB>\`.
  line=""
  local i
  for (( i=1; i < COMP_CWORD; i++ )); do
    case "\${COMP_WORDS[i]}" in
      -*) ;;
      *) line="\${line:+\$line }\${COMP_WORDS[i]}" ;;
    esac
  done

  case "\$line" in
${cases.join('\n')}
    *) words=${sq(roots.join(' '))} ;;
  esac

  COMPREPLY=( \$(compgen -W "\$words ${globals.join(' ')}" -- "\$cur") )
  return 0
}

complete -F ${fn} ${program.name}
`;
};

/* -------------------------------------------------------------------------- */

export const zshCompletions = (program: ProgramDef): string => {
  const entries = walk(program.commands);
  const fn = `_${program.name.replaceAll(/[^A-Za-z0-9]/g, '_')}`;
  const example = exampleCommand(program);

  const cases = entries.map((entry) => {
    const subcommands = visible(entry.command.subcommands ?? []).map((c) =>
      zshDescribe(c.name, c.summary),
    );
    const flags = visibleFlags(entry.command.flags).flatMap(([n, f]) =>
      flagSpellings(n, f).map((spelling) => zshDescribe(spelling, f.summary)),
    );
    return `      ${sq(entry.path.join(' '))}) offer=(${[...subcommands, ...flags].join(' ')}) ;;`;
  });

  const roots = visible(program.commands).flatMap((c) =>
    names(c).map((name) => zshDescribe(name, c.summary)),
  );
  const globals = visibleFlags(program.globalFlags).flatMap(([n, f]) =>
    flagSpellings(n, f).map((spelling) => zshDescribe(spelling, f.summary)),
  );

  return `#compdef ${program.name}
# zsh completion for ${program.name}
# Generated by \`${program.name} completions zsh\` — do not edit.
# Install:  ${program.name} completions zsh > "\${fpath[1]}/_${program.name}"
#     or:   eval "$(${program.name} completions zsh)"   # in ~/.zshrc

${fn}() {
  local -a path_words offer
  local i

  # The command path typed so far, flags dropped, so that
  # \`${program.name} --verbose ${example} <TAB>\` resolves the same as \`${program.name} ${example} <TAB>\`.
  for (( i = 2; i < CURRENT; i++ )); do
    [[ "\${words[i]}" == -* ]] && continue
    path_words+=("\${words[i]}")
  done

  case "\${(j: :)path_words}" in
${cases.join('\n')}
      *) offer=(${roots.join(' ')}) ;;
  esac

  offer+=(${globals.join(' ')})
  _describe -t ${program.name} ${sq(program.name)} offer
}

# Autoloaded from fpath, the file body *is* the function and zsh calls it.
# Sourced or eval'd from an rc file, it is not — so register it by hand.
if [[ "\$funcstack[1]" == "${fn}" ]]; then
  ${fn} "\$@"
else
  compdef ${fn} ${program.name}
fi
`;
};

