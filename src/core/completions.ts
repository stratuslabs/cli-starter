export const fishCompletions = (program: ProgramDef): string => {
  const lines: string[] = [
    `# fish completion for ${program.name}`,
    `# Generated by \`${program.name} completions fish\` — do not edit.`,
    `# Install:  ${program.name} completions fish > ~/.config/fish/completions/${program.name}.fish`,
    '',
    '# Disable file completion by default; commands opt back in where it makes sense.',
    `complete -c ${program.name} -f`,
    '',
  ];

  for (const entry of walk(program.commands)) {
    // fish matches on the sequence of non-flag words, which is exactly the
    // condition helper below — no manual position arithmetic.
    const condition =
      entry.path.length === 1
        ? '__fish_use_subcommand'
        : `__fish_seen_subcommand_from ${entry.path[entry.path.length - 2]}`;

    for (const name of names(entry.command)) {
      lines.push(
        `complete -c ${program.name} -n ${sq(condition)} -a ${sq(name)} -d ${sq(oneLine(entry.command.summary))}`,
      );
    }

    for (const [name, flag] of visibleFlags(entry.command.flags)) {
      const parts = [
        `complete -c ${program.name}`,
        `-n ${sq(`__fish_seen_subcommand_from ${entry.command.name}`)}`,
        `-l ${sq(name)}`,
        ...(flag.short === undefined ? [] : [`-s ${sq(flag.short)}`]),
        // -x is -r plus "no files". A flag with a fixed set of values wants
        // only those; one without (--config, --token) still wants the file
        // list, so it stays -r.
        ...(flag.type === 'string' ? [flag.choices === undefined ? '-r' : '-x'] : []),
        ...(flag.choices === undefined ? [] : [`-a ${sq(flag.choices.join(' '))}`]),
        `-d ${sq(oneLine(flag.summary))}`,
      ];
      lines.push(parts.join(' '));
    }
  }

  lines.push('');
  for (const [name, flag] of visibleFlags(program.globalFlags)) {
    const parts = [
      `complete -c ${program.name}`,
      `-l ${sq(name)}`,
      ...(flag.short === undefined ? [] : [`-s ${sq(flag.short)}`]),
      ...(flag.type === 'string' ? ['-r'] : []),
      `-d ${sq(oneLine(flag.summary))}`,
    ];
    lines.push(parts.join(' '));
  }

  return `${lines.join('\n')}\n`;
};

export const completionsFor = (program: ProgramDef, shell: Shell): string => {
  if (shell === 'bash') return bashCompletions(program);
  if (shell === 'zsh') return zshCompletions(program);
  return fishCompletions(program);
};
