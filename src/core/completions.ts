/**
 * Shell completion scripts, generated from the command registry.
 *
 * The same property that makes help un-driftable makes these un-driftable: the
 * registry is the only source, so a command that exists is completable and a
 * flag that exists is offered. Most CLIs hand-write a `_mycli` script that is
 * accurate on the day it is committed and wrong two releases later.
 *
 * These are **static** scripts. They list what the binary knew at the moment
 * they were generated rather than calling back into it on every keystroke,
 * which keeps completion instant and works when the binary is slow to start.
 * Told to `eval "$(acme completions zsh)"` from a shell rc, they are
 * regenerated on every new shell and cannot go stale in practice.
 *
 * What they deliberately do not do is complete *values* fetched from a server —
 * post ids, project names. That needs a callback, a cache, and a story for what
 * happens when you are offline or signed out, and it is not free enough to
 * include by default. `choices` on a flag is completed, because the registry
 * already knows it.
 */

import type { CommandDef, FlagDef, ProgramDef } from './command.ts';

export const SHELLS = ['bash', 'zsh', 'fish'] as const;
export type Shell = (typeof SHELLS)[number];

const visible = <T extends { hidden?: boolean }>(items: readonly T[]): T[] =>
  items.filter((item) => item.hidden !== true);

const visibleFlags = (flags: Record<string, FlagDef> = {}): [string, FlagDef][] =>
  Object.entries(flags).filter(([, flag]) => flag.hidden !== true);

/** Every name a command answers to. */
const names = (command: CommandDef): string[] => [command.name, ...(command.aliases ?? [])];

/**
 * A command and the path of words that reaches it.
 *
 * Flattened rather than recursed at render time so each shell's generator is a
 * loop over a list instead of its own tree walk — three tree walks is three
 * places for subcommands to be handled subtly differently.
 */
export interface CompletionEntry {
  /** `['notes']`, `['config', 'set']` — primary names only, no aliases. */
  path: string[];
  command: CommandDef;
}

export const walk = (commands: readonly CommandDef[], prefix: string[] = []): CompletionEntry[] =>
  visible(commands).flatMap((command) => {
    const path = [...prefix, command.name];
    return [{ path, command }, ...walk(command.subcommands ?? [], path)];
  });

/**
 * Single-quote for POSIX shells and fish alike.
 *
 * Inside single quotes every character is literal, so the only thing needing
 * care is a single quote itself: close, emit an escaped one, reopen.
 */
const sq = (value: string): string => `'${value.replaceAll("'", `'\\''`)}'`;

/**
 * Collapse a summary to one line of plain text.
 *
 * Summaries are prose written for help output. A newline would end the
 * statement it is embedded in, and backticks are a command substitution in
 * double-quoted contexts — neither is worth risking for the sake of preserving
 * formatting nobody sees in a completion menu.
 */
const oneLine = (value: string): string => value.replace(/\s+/g, ' ').replaceAll('`', "'").trim();

/**
 * zsh's `_describe` takes `value:description` pairs, so a colon inside the
 * description silently truncates it — or worse, shifts everything after it into
 * the wrong field. Summaries contain colons ("note: …", ratios, times), so this
 * is not hypothetical.
 */
const zshDescribe = (value: string, description: string): string =>
  sq(`${value}:${oneLine(description).replaceAll(':', '\\:')}`);

const flagSpellings = (name: string, flag: FlagDef): string[] =>
  flag.short === undefined ? [`--${name}`] : [`--${name}`, `-${flag.short}`];

